	public function status($idPasien,$tanggal){
		$q = $this->db->query("SELECT TO_CHAR(R.TGL_TRANSAKSI,'DD-MM-YYYY')TANGGAL,R.PASIEN_ID,P.INT_PASIEN_ID,R.TRANS_ID,R.TGL_TRANSAKSI TGL_MASUK,
                               SR01_GET_SUFFIX(P.PASIEN_ID) NAMA,P.NAMA_AKHIR,R.EPISODE_ID,R.POLI_ID,R.KELAS_ID,R.RUANGRWT_ID,
                               TO_CHAR(P.TGL_LAHIR,'dd-mm-yyyy') TGL_LAHIR, DECODE(P.SEX_ID,'L','LAKI-LAKI','PEREMPUAN')KELAMIN,
                               (SELECT MAX(D.TRANS_CO) FROM WEB_CO_DIAGNOSA_MS D WHERE D.EPISODE_ID=R.EPISODE_ID AND D.PASIEN_ID=R.PASIEN_ID AND D.SHOW_ITEM='1') TRANS_CO,
                               (SELECT MAX(K.KONSUL_KE) FROM WEB_CO_KONSUL_DT K WHERE  K.EPISODE_ID=R.EPISODE_ID AND K.PASIEN_ID=R.PASIEN_ID AND SHOW_ITEM='1') KONSUL
                               ,(SELECT DR.NAMA FROM SR01_MED_DOKTER_MS DR WHERE DR.LOKASI_ID='001' AND DR.DOKTER_ID=E.DOKTER_ID)DOKTER
                               ,(SELECT PO.KETERANGAN FROM SR01_MED_POLI_MS PO WHERE PO.LOKASI_ID='001' AND PO.POLI_ID=R.POLI_ID)POLI,
                                E.STATUS_EPISODE BAYAR,E.JENIS_EPISODE,TO_CHAR(E.TGL_KELUAR,'DD-MM-YYYY')TGL_KELUAR,
								(
								   CASE
										WHEN R.RUANGRWT_ID IS NOT NULL
											THEN E.RUANGRWT_ID
										ELSE ''
								   END
							   ) AS RUANGSAAT_INI
                               FROM SR01_GEN_PASIEN_MS P,SR01_KEU_TRANSAKSI_HD R,SR01_KEU_EPISODE E
                               WHERE R.JENIS_TR IN('000','001','002')
							   AND R.PASIEN_ID='". $idPasien ."'
							   AND R.AKTIF='1'
							   AND R.LOKASI_ID='001'
							   AND P.PASIEN_ID=R.PASIEN_ID
							   AND P.AKTIF='1'
							   AND P.LOKASI_ID='001'
							   AND E.EPISODE_ID=R.EPISODE_ID
							   AND E.PASIEN_ID=R.PASIEN_ID
							   AND E.STATUS_EPISODE <> '99'
							   AND E.AKTIF='1'
							   AND E.LOKASI_ID='001'
							   ".$tanggal."
							   ORDER BY R.CREATED_DATE DESC");
		return $q;
	}
