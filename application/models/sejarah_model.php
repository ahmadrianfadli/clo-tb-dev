	function selectAllResepHemo($EID,$TID){
		$q = $this->db->query("SELECT R.*,TO_CHAR(R.CREATED_DATE,'DD-MM-YYYY HH24:MI:SS') TANGGAL,
							   (SELECT D.NAMA FROM SR01_MED_DOKTER_MS D WHERE D.LOKASI_ID='001' AND D.DOKTER_ID=R.CREATED_BY) DOKTER,
							   (SELECT U.NAMA_USER FROM WEB_CO_USER U WHERE U.USER_ID=R.CREATED_BY AND U.SHOW_ITEM='1') PERAWAT,
							   (SELECT MAX(TRANS_VALID_ID) FROM SR01_FRM_VALIDASI_HD WHERE EPISODE_ID=R.EPISODE_ID AND TRANS_CO=R.TRANS_CO AND RESEP_KE=R.RESEP_KE AND AKTIF='1' AND STATUS_TR='00' ) VALID
