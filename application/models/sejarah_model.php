	public function tampil_pasien($isi){
		$q = $this->db->query("SELECT DISTINCT R.TGL_TRANSAKSI, TO_CHAR(R.TGL_TRANSAKSI,'dd-mm-yyyy') TGLMASUK,R.RUANGRWT_ID,P.PASIEN_ID,P.INT_PASIEN_ID,SR01_GET_SUFFIX(P.PASIEN_ID) NAMA,P.NAMA_AKHIR,P.ALAMAT1,HITUNG_UMUR(P.TGL_LAHIR, TRUNC(SYSDATE))UMUR,
							   TO_CHAR(P.TGL_LAHIR,'dd-mm-yyyy') TGL_LAHIR, (SELECT G.KETERANGAN FROM SR01_GEN_GLOBAL_MS G WHERE G.JENIS_ID='SEX' AND G.GLOBAL_ID=P.SEX_ID AND G.AKTIF='1') KELAMIN,
							   (SELECT PO.KETERANGAN FROM SR01_MED_POLI_MS PO WHERE PO.LOKASI_ID='001' AND PO.POLI_ID=R.POLI_ID) POLI
							   FROM SR01_KEU_TRANSAKSI_HD R,SR01_GEN_PASIEN_MS P,SR01_MED_DOKTER_MS D,SR01_KEU_EPISODE E
							   WHERE ".$isi."
							   AND R.JENIS_TR IN('000','001','002')
							   AND R.AKTIF='1'
							   AND R.LOKASI_ID='001'
							   AND P.PASIEN_ID=R.PASIEN_ID
							   AND P.AKTIF='1'
							   AND P.LOKASI_ID='001'
							   AND D.DOKTER_ID(+)=E.DOKTER_ID
							   --AND D.AKTIF='1'
							   AND D.LOKASI_ID='001'
							   AND E.STATUS_EPISODE<>'99'
							   AND E.EPISODE_ID=R.EPISODE_ID
							   AND E.PASIEN_ID=R.PASIEN_ID
							   AND E.AKTIF='1'
							   AND E.LOKASI_ID='001'
							   ORDER BY R.TGL_TRANSAKSI DESC");
		return $q;
	}
